# update-mupdf-stamp.ps1
# Writes vcpkg-overlay/ports/libmupdf/source-stamp.txt describing the exact
# state of the local MuPDF checkout (HEAD commit, submodule commits, hash of
# uncommitted changes).
#
# vcpkg hashes every file in a port directory into the package ABI, but it
# knows nothing about the external source tree the overlay port builds from.
# Putting this stamp in the port directory makes any change to the MuPDF
# checkout change the ABI, so vcpkg rebuilds libmupdf instead of reusing a
# stale installed package or binary-cache entry.
#
# Run before any `vcpkg install` (build-dependencies.ps1 and build-app.ps1
# call it automatically).

[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$MupdfSourceDir
)

$ErrorActionPreference = "Stop"
$repoRoot  = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$stampFile = Join-Path $repoRoot "vcpkg-overlay\ports\libmupdf\source-stamp.txt"

if (-not (Test-Path (Join-Path $MupdfSourceDir ".git"))) {
    throw "$MupdfSourceDir is not a git checkout; cannot stamp MuPDF source state."
}

function Invoke-Git([string[]]$GitArgs) {
    $out = & git -C $MupdfSourceDir @GitArgs
    if ($LASTEXITCODE -ne 0) { throw "git $($GitArgs -join ' ') failed in $MupdfSourceDir" }
    return ($out -join "`n")
}

$head       = Invoke-Git @("rev-parse", "HEAD")
$submodules = Invoke-Git @("submodule", "status", "--recursive")
# Uncommitted changes to tracked files of the top-level repo.  Dirty
# submodule working trees are ignored; submodule commit changes are covered
# by `submodule status` above.  Untracked files (e.g. the CMakeLists.txt the
# portfile copies in) are not part of `git diff`.
$diff       = Invoke-Git @("diff", "HEAD", "--ignore-submodules=dirty", "--binary")

$sha = [System.Security.Cryptography.SHA256]::Create()
$diffHash = -join ($sha.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($diff)) |
                   ForEach-Object { $_.ToString("x2") })

$content = @(
    "# Generated by scripts/Windows/update-mupdf-stamp.ps1 -- do not edit."
    "# Part of the libmupdf port ABI: changes here force vcpkg to rebuild."
    "source: $((Resolve-Path $MupdfSourceDir).Path)"
    "head: $head"
    "diff-sha256: $diffHash"
    "submodules:"
    $submodules
) -join "`n"

$previous = if (Test-Path $stampFile) { Get-Content $stampFile -Raw } else { $null }
if ($previous -ne "$content`n") {
    [System.IO.File]::WriteAllText($stampFile, "$content`n")
    Write-Host ">> MuPDF source stamp updated ($($head.Substring(0, 10))) -- libmupdf will be rebuilt"
} else {
    Write-Host ">> MuPDF source stamp unchanged ($($head.Substring(0, 10)))"
}
